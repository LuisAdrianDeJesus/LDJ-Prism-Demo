Sys.unsetenv("LDJ_PRISM_MODE")
chrome <- Sys.which("google-chrome")
if(nzchar(chrome)) Sys.setenv(CHROMOTE_CHROME=chrome)
app <- shinytest2::AppDriver$new(app_dir=".",name="complete-style",load_timeout=90000)
tryCatch({
  app$set_inputs(inspector="Colores",axis_y_mode="manual",axis_y_min=5,axis_y_max=105,
    axis_y_step=10,width=8.1,height=12.4,preview_zoom=120,wait_=FALSE)
  app$wait_for_idle(timeout=90000)
  dir.create("test-artifacts",showWarnings=FALSE)
  path <- file.path("test-artifacts","complete-style.json")
  app$get_download("style_json",filename=path)
  before <- jsonlite::read_json(path)
  stopifnot(before$settings$axis_y_min==5,before$settings$axis_y_max==105,before$settings$height==12.4)
  restored <- shinytest2::AppDriver$new(app_dir=".",name="complete-style-restored",load_timeout=90000)
  restored$set_inputs(inspector="Colores",wait_=FALSE)
  restored$upload_file(style_import=path)
  restored$wait_for_js("Number(document.getElementById('height').value) === 12.4",timeout=30000)
  actual <- tempfile(fileext=".json")
  restored$get_download("style_json",filename=actual)
  stopifnot(identical(before,jsonlite::read_json(actual)))
  cat("Versioned style stores and restores axes and dimensions in a fresh browser session: PASS\n")
},finally={if(exists("restored")) restored$stop();app$stop()})
